// Write apps/gm-react/.env.local from the deployed SSM parameters for a stage, so
// `vite build` / `vite dev` pick up VITE_* cloud coordinates. Local-first: if you
// never run this, the app builds with no cloud config and all cloud UI stays hidden.
//
//   node scripts/pull-cloud-env.mjs [stage]        # default stage: dev
//   DNDTOOLS_PROFILE=dndtools DNDTOOLS_REGION=ca-central-1 node scripts/pull-cloud-env.mjs dev
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const stage = process.argv[2] || 'dev';
const project = process.env.DNDTOOLS_PROJECT || 'dndtools';
// Default hard to the dndtools profile; the ambient AWS_PROFILE may be unrelated.
const profile = process.env.DNDTOOLS_PROFILE || 'dndtools';
const region = process.env.DNDTOOLS_REGION || 'ca-central-1';

const ssm = (name) =>
	execFileSync(
		'aws',
		[
			'ssm',
			'get-parameter',
			'--name',
			`/${project}/${stage}/${name}`,
			'--query',
			'Parameter.Value',
			'--output',
			'text',
			'--profile',
			profile,
			'--region',
			region,
		],
		{ encoding: 'utf8' },
	).trim();

// Tolerant read — a not-yet-deployed stack's param is absent; return '' rather than throwing so the
// app still gets the params for the stacks that ARE deployed (cloud features gate on presence).
const ssmOptional = (name) => {
	try {
		return ssm(name);
	} catch {
		console.warn(`  (optional param /${project}/${stage}/${name} not found — skipping)`);
		return '';
	}
};

const env = {
	VITE_CLOUD_REGION: region,
	VITE_COGNITO_USER_POOL_ID: ssm('identity/user-pool-id'),
	VITE_COGNITO_CLIENT_ID: ssm('identity/app-client-id'),
	VITE_SIGNALING_WS_URL: ssm('signaling/ws-url'),
	VITE_SYNC_API_URL: ssmOptional('sync/api-url'),
	VITE_APP_API_URL: ssmOptional('app-api/url'),
	VITE_PUBLIC_APP_URL: ssmOptional('web/url'),
	// Must mirror web-hosting's connect-src. A configured custom provider is
	// rejected fail-closed unless its exact origin appears in this list.
	VITE_AI_ALLOWED_ORIGINS: ssmOptional('web/ai-connect-origins'),
	// Google Docs vault-source OAuth client id (manual setup — docs/runbooks/google-oauth-setup.md).
	// Absent ⇒ the Google Docs source option stays hidden (fail closed).
	VITE_GOOGLE_CLIENT_ID: ssmOptional('google/client-id'),
};

const here = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(here, '..', '.env.local');
const body =
	`# Generated by scripts/pull-cloud-env.mjs (stage=${stage}). Do not commit.\n` +
	Object.entries(env)
		.map(([k, v]) => `${k}=${v}`)
		.join('\n') +
	'\n';
writeFileSync(outPath, body);
console.log(`wrote ${outPath} for stage=${stage}:`);
console.log(body);
